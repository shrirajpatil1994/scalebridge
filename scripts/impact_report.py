"""Generate docs/IMPACT.md from the indexed CAG reports.

Method (conservative by design):
- A "finding sentence" is one sentence that contains BOTH a leakage-pattern phrase and a rupee amount.
- Amounts are attributed only from finding sentences, never from whole passages.
- Duplicates are removed per report by (pattern, amount), because executive summaries
  repeat the chapter findings.
- Totals are "amounts cited in audit findings", NOT a measure of loss: they mix losses,
  irregular payments, unrecovered dues and idle balances, and some are counted at gross value.
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scalebridge.answer import extractive  # noqa: E402
from scalebridge.retrieve import load_index  # noqa: E402
from scalebridge.taxonomy import TAXONOMY, _COMPILED, is_toc_like  # noqa: E402

AMT = re.compile(r"(?:₹|`|Rs\.?)\s?([\d,]+(?:\.\d+)?)\s?(crore|lakh)", re.I)


def to_crore(num: str, unit: str) -> float:
    v = float(num.replace(",", ""))
    return v if unit.lower() == "crore" else v / 100.0


def sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.;])\s+(?=[A-Z(])", text) if len(s.strip()) > 40]


def main() -> None:
    idx = load_index()
    findings: dict[tuple, dict] = {}
    for d in idx.docs:
        text = d["text"].replace("` ", "₹ ")
        if is_toc_like(text) or sum(ord(c) > 0x900 for c in text[:300]) > 30:  # skip TOC and Marathi duplicates
            continue
        for s in sentences(text):
            amts = AMT.findall(s)
            if not amts:
                continue
            for key, regs in _COMPILED.items():
                m = next((r.search(s) for r in regs if r.search(s)), None)
                if not m:
                    continue
                # amount nearest to the pattern phrase (not the largest in the sentence)
                ams = [(abs(a.start() - m.start()), to_crore(a.group(1), a.group(2))) for a in AMT.finditer(s)]
                cr = min(ams)[1]
                k = (d["report_id"], key, round(cr, 2))
                if k not in findings:
                    findings[k] = {"report_id": d["report_id"], "report": d["report_title"], "file": d["file"],
                                   "page": d["page"], "pattern": key, "crore": cr, "sentence": s[:400]}
                break
    all_rows = list(findings.values())
    SYSTEM_LEVEL = 1000.0  # ₹ crore: state-wide balances/receivables, not a single work, contract or payment
    rows = [r for r in all_rows if r["crore"] < SYSTEM_LEVEL]
    system_rows = sorted([r for r in all_rows if r["crore"] >= SYSTEM_LEVEL], key=lambda r: -r["crore"])
    by_pat = defaultdict(lambda: {"n": 0, "crore": 0.0, "reports": set()})
    for r in rows:
        b = by_pat[r["pattern"]]; b["n"] += 1; b["crore"] += r["crore"]; b["reports"].add(r["report_id"])
    reports = json.loads((ROOT / "data" / "manifest.json").read_text())
    n_files = sum(len(r.get("files", [])) for r in reports)
    total = sum(r["crore"] for r in rows)

    demo_qs = [
        "Undue benefit to developers through excess TDR in slum rehabilitation schemes",
        "Which additional works did CIDCO award to existing contractors without inviting tenders?",
        "Findings on the BMC COVID jumbo centre contracts 2020",
    ]
    out = []
    w = out.append
    w("# ScaleBridge: what published audits already tell us, and what changes with AI\n")
    w("*Generated by `scripts/impact_report.py` from the indexed corpus. Every figure below links back to a report and page; re-run the script to reproduce.*\n")
    w("## 1. The headline\n")
    w(f"From **{len(reports)} published CAG reports** on Maharashtra ({n_files} PDFs, {len(idx.docs):,} page-anchored passages), "
      f"ScaleBridge extracted **{len(rows)} distinct transaction-level audit findings**: individual works, contracts, payments or recoveries "
      f"where the leakage pattern and the rupee amount appear in the same sentence. Together they cite **₹{total:,.0f} crore**. "
      f"A further **{len(system_rows)} system-level findings** (state-wide unspent balances and receivables of ₹1,000 crore or more) are listed separately in section 4 and not added to this total.\n")
    w("> **Read this number carefully.** It is the sum of amounts *cited in audit findings*, not a measured loss. It mixes irregular "
      "payments, unrecovered dues, idle balances and contract values that audit questioned. Its value is as a map of *where to look*: "
      "it took minutes to produce, against weeks of manual reading.\n")
    w("## 2. Where the money sits, by pattern\n")
    w("| Pattern | Findings | Amount cited (₹ crore) | Reports |")
    w("|---|---:|---:|---:|")
    for key, b in sorted(by_pat.items(), key=lambda kv: -kv[1]["crore"]):
        w(f"| {TAXONOMY[key]['label']} | {b['n']} | {b['crore']:,.1f} | {len(b['reports'])} |")
    w("")
    w("## 3. The ten largest cited findings\n")
    w("| # | Pattern | ₹ crore | Finding (quoted) | Source |")
    w("|---:|---|---:|---|---|")
    for i, r in enumerate(sorted(rows, key=lambda r: -r["crore"])[:10], 1):
        q = r["sentence"].replace("|", "/").replace("\n", " ")
        w(f"| {i} | {TAXONOMY[r['pattern']]['label']} | {r['crore']:,.2f} | \"{q[:220]}{'…' if len(q) > 220 else ''}\" | {r['report'][:60]}, p.{r['page']} |")
    w("")
    w("## 4. System-level findings (not added to the total)\n")
    w("These describe state-wide balances or portfolios, not single transactions. They matter for financial discipline but should not be read as leakage.\n")
    w("| ₹ crore | Finding (quoted) | Source |")
    w("|---:|---|---|")
    for r in system_rows[:8]:
        q = r["sentence"].replace("|", "/").replace("\n", " ")
        w(f"| {r['crore']:,.0f} | \"{q[:200]}{'…' if len(q) > 200 else ''}\" | {r['report'][:60]}, p.{r['page']} |")
    w("")
    w("## 5. What it looks like in use\n")
    for q in demo_qs:
        a = extractive(q, idx, k=3)
        w(f"**Q: {q}**\n")
        w("```")
        w(a.text)
        w("```\n")
    w("The last question correctly returns **NOT FOUND**: the 2023 BMC special audit was tabled in the legislature and is not yet in the corpus. "
      "The system says so instead of guessing.\n")
    w("## 6. Impact: before and after\n")
    w("| Task | Today (manual) | With ScaleBridge M4 |")
    w("|---|---|---|")
    w("| Find every past audit finding on a body, scheme or contractor | Days to weeks: download reports, read chapters, cross-reference | Seconds: one query, cited passages across all reports |")
    w("| Spot recurring patterns across years and bodies | Rarely done: reports are read one at a time | Pattern table across the whole archive, with evidence phrases |")
    w("| Prepare for a new audit or reply to an observation | Search old files by memory | Pull prior findings and the agency's past replies, with pages |")
    w("| Avoid repeating a known failure in a new tender | Depends on institutional memory | Check the tender's features against documented failure patterns (M2) |")
    w("")
    w("**Who benefits**")
    w("- **Agencies (BMC, MHADA, SRA, CIDCO, MMRDA):** know their audit history before the auditor arrives; settle inspection-report paras faster.")
    w("- **Auditors and the CAG:** a public-data complement to CAG-LLM and CDMA, useful for desk reviews before fieldwork.")
    w("- **Legislators, PAC staff, journalists, citizens:** a searchable, cited view of what audits have already said.")
    w("")
    w("## 7. Method and limits\n")
    w("- Finding = one sentence containing a pattern phrase and a rupee amount; the amount nearest the pattern phrase is used; duplicates per report removed by (pattern, amount).")
    w("- Transaction-level = under ₹1,000 crore per finding; larger figures are treated as system-level balances and excluded from the headline.")
    w("- Amounts are as cited by audit and may overlap where one finding is reported in several places.")
    w("- **Manual spot-check (25 Nov 2026):** of the ten largest findings in section 3, 8 attach the right amount to the finding; 2 attach a contextual figure (the Nerul-Uran project cost, and the monorail O&M contract value) rather than the amount at issue. Treat individual rows as leads to verify, not conclusions.")
    w("- Rule-based tagging is transparent but imperfect; precision has not yet been measured (next step: 100 hand-labelled passages).")
    w("- Retrieval evaluation: 100% hit@5 on 18 development and 9 held-out lookups, 6/6 not-found cases (self-authored; see `eval/results.md`).")
    w("- Coverage: 15 reports; scanned PDFs pending OCR; 2023 BMC special audit not yet included.")
    (ROOT / "docs" / "IMPACT.md").write_text("\n".join(out))
    print(f"wrote docs/IMPACT.md: {len(rows)} findings, ₹{total:,.0f} crore cited")


if __name__ == "__main__":
    main()
